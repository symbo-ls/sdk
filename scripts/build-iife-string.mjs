/**
 * Emit `dist/sdk.iife-string.js` — the SDK IIFE source as a default-exported
 * JS string, plus the `version` it was built from.
 *
 * Lets a host inline the bundle with no filesystem access:
 *
 *   import * as sdkIife from '@symbo.ls/sdk/iife-string'
 *   html += `<script>${sdkIife.default}</script>`
 *
 * NAMESPACE import on purpose, and consumers must keep it that way: a named
 * import of a missing export is a hard LINK-time error in ESM, so a host that
 * still resolves an older build of this package would fail to start rather
 * than degrade. Same contract `smbls/iife-string` already documents.
 *
 * Regenerated by `npm run build:iife`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = resolve(root, 'dist/sdk.iife.js');
const outputPath = resolve(root, 'dist/sdk.iife-string.js');

const iife = readFileSync(inputPath, 'utf8');
const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));

// The global the IIFE assigns itself to travels WITH the source. A host that
// inlines this bundle has to name the binding to hand `registerHostPackages`,
// and re-deriving it from minified source is guesswork.
const out =
  '// Auto-generated by scripts/build-iife-string.mjs — do not edit.\n' +
  `export const version = ${JSON.stringify(version)};\n` +
  `export const globalName = ${JSON.stringify('SymbolsSDK')};\n` +
  `export const specifier = ${JSON.stringify('@symbo.ls/sdk')};\n` +
  `export default ${JSON.stringify(iife)};\n`;
writeFileSync(outputPath, out);

console.log(
  `[build-iife-string] wrote ${outputPath} (${iife.length} bytes IIFE, v${version})`,
);
